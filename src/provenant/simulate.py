"""Synthetic hot-fire recordings for the demo project and tests.

The profile is physically motivated rather than random: chamber pressure is
an under-damped second-order step (start-up overshoot), thrust and mass flow
follow chamber pressure through the analysis model, and throat wall
temperature is a first-order thermal response. Noise is seeded, so every
generated file is byte-for-byte reproducible.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass, field

from .physics import LIQUID_ENGINE
from .units import get_unit

PSI = get_unit("psi")
LBF = get_unit("lbf")
DEG_C = get_unit("degC")


@dataclass
class FiringProfile:
    chamber_pressure_bar: float
    burn_s: float
    wall_temp_steady_k: float
    design: dict[str, float]  # SI inputs for the analysis model
    seed: int = 0
    sample_rate_hz: float = 100.0
    pre_s: float = 1.0
    post_s: float = 3.0
    damping: float = 0.56
    natural_freq: float = 25.0  # rad/s
    pressure_column: str = "PT-101"
    abort_at_s: float | None = None  # burn time at which the firing is cut short
    dropouts: list[tuple[str, float, float]] = field(default_factory=list)  # (column, t0, t1)


def _step_response(t: float, zeta: float, wn: float) -> float:
    """Unit step response of an under-damped second-order system."""
    if t <= 0:
        return 0.0
    wd = wn * math.sqrt(1.0 - zeta * zeta)
    phi = math.acos(zeta)
    return 1.0 - math.exp(-zeta * wn * t) * math.sin(wd * t + phi) / math.sqrt(1.0 - zeta * zeta)


def generate_hot_fire(profile: FiringProfile) -> str:
    rng = random.Random(profile.seed)
    design = dict(profile.design, chamber_pressure_nominal=profile.chamber_pressure_bar * 1e5)
    nominal = LIQUID_ENGINE.compute(design)
    pc_nom = profile.chamber_pressure_bar * 1e5

    burn = profile.burn_s if profile.abort_at_s is None else min(profile.burn_s, profile.abort_at_s)
    t_ign = profile.pre_s
    t_cut = t_ign + burn
    total = t_cut + profile.post_s
    dt = 1.0 / profile.sample_rate_hz
    n = round(total / dt) + 1
    level_at_cut = _step_response(t_cut - t_ign, profile.damping, profile.natural_freq)

    header = ["time_s", profile.pressure_column, "LC-01", "TC-205", "FM-01"]
    lines = ["# Synthetic hot-fire recording generated by provenant.simulate", ",".join(header)]
    wall = 293.15
    drift_phase = rng.uniform(0, 2 * math.pi)
    for i in range(n):
        t = i * dt
        if t < t_ign:
            level = 0.0
        elif t < t_cut:
            level = _step_response(t - t_ign, profile.damping, profile.natural_freq)
        else:
            level = level_at_cut * math.exp(-(t - t_cut) / 0.12)
        drift = 1.0 + 0.004 * math.sin(0.35 * t + drift_phase)
        pc = pc_nom * level * drift
        pc_meas = max(0.0, pc + rng.gauss(0, 0.003 * pc_nom * (0.2 + level)) + 0.03e5)
        thrust = nominal["thrust_vac"] * (pc / pc_nom) + rng.gauss(0, 0.003 * nominal["thrust_vac"] * (0.1 + level))
        flow = nominal["mass_flow"] * (pc / pc_nom) + rng.gauss(0, 0.004 * nominal["mass_flow"] * (0.1 + level))

        firing = t_ign <= t < t_cut
        target = profile.wall_temp_steady_k if firing else 293.15
        tau = 5.0 if firing else 18.0
        wall += (target - wall) * (1.0 - math.exp(-dt / tau))
        wall_meas = wall + rng.gauss(0, 0.8)

        values = {
            "time_s": f"{t:.3f}",
            profile.pressure_column: f"{PSI.from_si(pc_meas):.2f}",
            "LC-01": f"{LBF.from_si(max(thrust, 0.0)):.1f}",
            "TC-205": f"{DEG_C.from_si(wall_meas):.1f}",
            "FM-01": f"{max(flow, 0.0):.4f}",
        }
        for column, d0, d1 in profile.dropouts:
            if d0 <= t <= d1:
                values[column] = ""
        lines.append(",".join(values[h] for h in header))
    return "\n".join(lines) + "\n"
